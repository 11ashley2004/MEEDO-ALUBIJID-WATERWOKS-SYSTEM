'use client'

import { useDebouncedSearch } from '@/lib/hooks/use-debounced-search'

import { TablePagination } from '@/components/shared-ui/pagination'
import { PageHeading } from '@/components/shared-ui/page-heading'

import { useState, useEffect, useCallback, useMemo } from 'react'
import { useRouter } from 'next/navigation'
import { FileWarning, Eye, Search, X, Calendar, Users, ShieldAlert, MoreHorizontal, FileSpreadsheet, Printer, Zap } from 'lucide-react'
import { Spinner } from '@/components/ui/spinner'
import { Button } from '@/components/ui/button'
import { Input } from '@/components/ui/input'
import {
  Table, TableBody, TableCell, TableHead, TableHeader, TableRow,
} from '@/components/ui/table'
import {
  Select, SelectContent, SelectItem, SelectTrigger, SelectValue,
} from '@/components/ui/select'
import {
  DropdownMenu,
  DropdownMenuContent,
  DropdownMenuItem,
  DropdownMenuLabel,
  DropdownMenuSeparator,
  DropdownMenuTrigger,
} from '@/components/ui/dropdown-menu'
import { Badge } from '@/components/ui/badge'
import { cn } from '@/lib/utils'
import { toast } from 'sonner'
import {
  getNoticesOfDisconnection,
  autoGenerateDisconnectionNotices,
  type NoticeOfDisconnection,
} from '@/lib/actions/disconnection-notice/disconnection-notice.actions'
import { PdfExportButton } from '@/components/admin-ui/disconnection-notice/pdf-export'
import { BillingDisconnectionNoticeModal } from '@/components/admin-ui/disconnection-notice/BillingDisconnectionNoticeModal'

const PAGE_SIZE_OPTIONS = [10, 25, 50, 100]

// ─── Helpers ──────────────────────────────────────────────────────────────────

function formatDateTime(d: string): string {
  return new Date(d).toLocaleString('en-US', {
    year: 'numeric', month: 'short', day: 'numeric',
    hour: '2-digit', minute: '2-digit',
  })
}

function formatPeriod(periodStart: string): string {
  if (!periodStart) return '—'
  return new Date(periodStart).toLocaleDateString('en-US', {
    month: 'long', year: 'numeric',
  })
}

function formatPeso(n: number): string {
  return new Intl.NumberFormat('en-PH', {
    style: 'currency', currency: 'PHP',
  }).format(n)
}

// ─── Main Page ────────────────────────────────────────────────────────────────

const DisconnectionNoticePage = () => {
  const router = useRouter()

  const [notices, setNotices] = useState<NoticeOfDisconnection[]>([])
  const [isLoading, setIsLoading] = useState(true)
  const [search, setSearch] = useState('')
  const debouncedSearch = useDebouncedSearch(search)
  const [searchFocused, setSearchFocused] = useState(false)
  const [page, setPage] = useState(1)
  const [pageSize, setPageSize] = useState(10)
  const [isAutoGenerating, setIsAutoGenerating] = useState(false)

  // ── Fetch ──────────────────────────────────────────────────────────────────
  const fetchData = useCallback(async () => {
    setIsLoading(true)
    try {
      const result = await getNoticesOfDisconnection()
      if (result.status === 'success') {
        setNotices(result.data ?? [])
      } else {
        toast.error(result.message ?? 'Failed to load notices')
      }
    } catch {
      toast.error('An unexpected error occurred')
    } finally {
      setIsLoading(false)
    }
  }, [])

  useEffect(() => { fetchData() }, [fetchData])
  useEffect(() => { setPage(1) }, [debouncedSearch])

  // ── Client filter ──────────────────────────────────────────────────────────
  const filtered = useMemo(() => {
    const q = debouncedSearch.trim().toLowerCase()
    if (!q) return notices
    return notices.filter(
      (n) =>
        n.notice_no.toLowerCase().includes(q) ||
        (n.generated_by_name ?? '').toLowerCase().includes(q)
    )
  }, [notices, debouncedSearch])

  const totalPages = Math.max(1, Math.ceil(filtered.length / pageSize))
  const safePage = Math.min(page, totalPages)
  const paginated = useMemo(
    () => filtered.slice((safePage - 1) * pageSize, safePage * pageSize),
    [filtered, safePage, pageSize]
  )

  const hasActiveFilters = debouncedSearch.trim().length > 0
  const isSearchActive = search.length > 0 || searchFocused
  const isNonDefaultPageSize = pageSize !== 10

  // ── Action Handlers ────────────────────────────────────────────────────────
  const handleView = (noticeId: string) => {
    router.push(`/clerk/notice-disconnection/${noticeId}`)
  }

  const handleAutoGenerate = async () => {
    setIsAutoGenerating(true)
    try {
      const result = await autoGenerateDisconnectionNotices()
      if (result.status === 'error') {
        toast.error(result.message ?? 'Failed to notify consumers')
        return
      }
      toast.success(result.message ?? 'Consumers notified')
      await fetchData()
    } catch {
      toast.error('Failed to notify consumers')
    } finally {
      setIsAutoGenerating(false)
    }
  }


  // ─── Skeleton ───────────────────────────────────────────────────────────────
  const renderSkeleton = () =>
    [...Array(5)].map((_, i) => (
      <TableRow key={i} className="border-t border-slate-100">
        {[...Array(6)].map((_, j) => (
          <TableCell key={j} className="py-3">
            <div className="h-3.5 w-full bg-slate-100 animate-pulse rounded-full" />
          </TableCell>
        ))}
      </TableRow>
    ))

  // ─── Render ────────────────────────────────────────────────────────────────
  return (
    <div className="w-full space-y-5 lg:mb-0 mb-15">

      {/* Header */}
      <PageHeading title="Disconnection Notices" description="Track all notices of disconnection generated from the current billing period" />
{/* Toolbar */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3">
        <div className="flex flex-col sm:flex-row sm:items-center gap-2 flex-1">

          {/* Search */}
          <div className="relative w-full min-w-0 sm:w-auto sm:flex-1 sm:max-w-sm">
            <Search
              className={cn(
                'absolute left-3 top-1/2 -translate-y-1/2 h-3.5 w-3.5 transition-colors',
                isSearchActive ? 'text-violet-400' : 'text-slate-300',
              )}
            />
            <Input
              placeholder="Search by notice # or generated by..."
              value={search}
              onChange={(e) => { setSearch(e.target.value); setPage(1) }}
              onFocus={() => setSearchFocused(true)}
              onBlur={() => setSearchFocused(false)}
              className={cn(
                'pl-9 h-8 rounded-md text-xs bg-white border-slate-200 text-slate-700',
                'placeholder:text-slate-300 focus-visible:ring-0 focus-visible:ring-offset-0 transition-colors',
                isSearchActive
                  ? 'border-violet-400 ring-2 ring-violet-100'
                  : 'hover:border-violet-200',
              )}
            />
            {search && (
              <button
                onClick={() => { setSearch(''); setPage(1) }}
                className="absolute right-2.5 top-1/2 -translate-y-1/2 p-0.5 rounded-full hover:bg-slate-100"
              >
                <X className="h-3 w-3 text-slate-400" />
              </button>
            )}
          </div>

          {hasActiveFilters && (
            <button
              onClick={() => { setSearch(''); setPage(1) }}
              className="inline-flex items-center gap-1 h-8 px-2.5 rounded-md text-xs text-slate-400 hover:text-violet-600 hover:bg-violet-50"
            >
              <X className="h-3 w-3" /> Clear
            </button>
          )}
        </div>

        <div className="flex items-center gap-2 self-start sm:self-auto">
          {!isLoading && (
            <Badge
              variant="outline"
              className="h-8 px-3 rounded-md text-[11px] font-medium text-slate-500 border-slate-200 bg-white whitespace-nowrap"
            >
              {notices.length} total notice{notices.length !== 1 ? 's' : ''}
            </Badge>
          )}
          <Button
            variant="outline"
            size="sm"
            disabled={isAutoGenerating}
            onClick={handleAutoGenerate}
            className="h-8 rounded-md text-xs font-medium gap-1.5 border-rose-200 text-rose-700 hover:bg-rose-50"
          >
            {isAutoGenerating ? (
              <Spinner />
            ) : (
              <Zap className="h-3.5 w-3.5" />
            )}
            Notify eligible
          </Button>
          <BillingDisconnectionNoticeModal onSuccess={fetchData} />
        </div>
      </div>

      {/* Table */}
      <div className="bg-white border border-slate-200 rounded-md overflow-hidden">

        {/* Table header bar */}
        <div className="px-5 py-3 border-b border-slate-100 bg-gradient-to-r from-violet-50 to-white flex items-center justify-between">
          <div className="flex items-center gap-2">
            <div className="h-6 w-6 rounded-md bg-violet-100 border border-violet-200 flex items-center justify-center">
              <FileWarning className="h-3 w-3 text-violet-500" />
            </div>
            <p className="text-xs text-slate-500">
              {isLoading ? (
                <span className="inline-block h-3 w-24 bg-slate-100 animate-pulse rounded-full" />
              ) : (
                <>
                  <span className="font-semibold text-slate-700">{filtered.length}</span>
                  {' '}notice{filtered.length !== 1 ? 's' : ''}
                  {hasActiveFilters && <span className="text-slate-400"> · filtered</span>}
                </>
              )}
            </p>
          </div>

          {/* Rows per page */}
          <div className="flex items-center gap-2 text-[11px] text-slate-400">
            <span className="hidden sm:inline">Rows per page</span>
            <Select
              value={String(pageSize)}
              onValueChange={(v) => { setPageSize(Number(v)); setPage(1) }}
            >
              <SelectTrigger
                className={cn(
                  'h-7 w-[58px] rounded-md text-[11px] bg-white border-slate-200 text-slate-500',
                  'focus:ring-0 focus:ring-offset-0 hover:border-violet-300',
                  isNonDefaultPageSize && 'border-violet-300 text-violet-600',
                )}
              >
                <SelectValue />
              </SelectTrigger>
              <SelectContent className="bg-white border border-slate-200 rounded-md">
                {PAGE_SIZE_OPTIONS.map((s) => (
                  <SelectItem
                    key={s}
                    value={String(s)}
                    className="text-xs cursor-pointer focus:bg-violet-50 focus:text-violet-700 dark:focus:bg-accent dark:focus:text-accent-foreground"
                  >
                    {s}
                  </SelectItem>
                ))}
              </SelectContent>
            </Select>
          </div>
        </div>

        <div className="overflow-x-auto">
          <Table>
            <TableHeader>
              <TableRow className="bg-slate-50/40">
                <TableHead className="text-[9px] font-bold text-slate-400 uppercase tracking-wider">Notice #</TableHead>
                <TableHead className="text-[9px] font-bold text-slate-400 uppercase tracking-wider">Generated By</TableHead>
                <TableHead className="text-[9px] font-bold text-slate-400 uppercase tracking-wider">Total Accounts</TableHead>
                <TableHead className="text-[9px] font-bold text-slate-400 uppercase tracking-wider">Reading Period</TableHead>
                <TableHead className="text-[9px] font-bold text-slate-400 uppercase tracking-wider">Generated At</TableHead>
                <TableHead className="w-12">
                  <span className="sr-only">Actions</span>
                </TableHead>
              </TableRow>
            </TableHeader>
            <TableBody>

              {/* Loading skeletons */}
              {isLoading && renderSkeleton()}

              {/* Empty — no notices */}
              {!isLoading && notices.length === 0 && (
                <TableRow>
                  <TableCell colSpan={6} className="h-64 text-center">
                    <div className="flex flex-col items-center gap-3">
                      <div className="h-12 w-12 rounded-md bg-violet-50 border border-violet-100 flex items-center justify-center">
                        <FileWarning className="h-5 w-5 text-violet-300" />
                      </div>
                      <div>
                        <p className="text-sm font-semibold text-slate-600">No disconnection notices</p>
                        <p className="text-xs text-slate-400 mt-1 max-w-xs">
                          Notices appear here once generated from the current billing period.
                        </p>
                      </div>
                    </div>
                  </TableCell>
                </TableRow>
              )}

              {/* Empty — no results */}
              {!isLoading && notices.length > 0 && filtered.length === 0 && (
                <TableRow>
                  <TableCell colSpan={6} className="h-64 text-center">
                    <div className="flex flex-col items-center gap-3">
                      <div className="h-12 w-12 rounded-md bg-violet-50 border border-violet-100 flex items-center justify-center">
                        <Search className="h-5 w-5 text-violet-300" />
                      </div>
                      <div>
                        <p className="text-sm font-semibold text-slate-600">No results</p>
                        <p className="text-xs text-slate-400 mt-1">No notices match your filters.</p>
                      </div>
                      <button
                        onClick={() => { setSearch(''); setPage(1) }}
                        className="inline-flex items-center gap-1.5 h-7 px-3 rounded-md text-xs font-medium text-violet-600 bg-violet-50 border border-violet-200 hover:bg-violet-100"
                      >
                        Clear filters
                      </button>
                    </div>
                  </TableCell>
                </TableRow>
              )}

              {/* Data rows */}
              {!isLoading && paginated.map((notice) => (
                <TableRow
                  key={notice.notice_id}
                  className="border-t border-slate-100 hover:bg-violet-50/40 transition-colors"
                >
                  <TableCell className="py-3">
                    <span className="font-mono text-[12.5px] font-semibold text-violet-600">
                      {notice.notice_no}
                    </span>
                  </TableCell>

                  <TableCell className="py-3">
                    <div className="flex items-center gap-2">
                      <div className="h-7 w-7 rounded-md bg-violet-100 flex items-center justify-center shrink-0">
                        <ShieldAlert className="h-3.5 w-3.5 text-violet-600" />
                      </div>
                      <div>
                        <p className="text-[12.5px] font-medium text-slate-800">
                          {notice.generated_by_name ?? '—'}
                        </p>
                      </div>
                    </div>
                  </TableCell>

                  <TableCell className="py-3">
                    <div className="flex items-center gap-1.5">
                      <Users className="h-3.5 w-3.5 text-slate-400" />
                      <Badge variant="outline" className="rounded-md bg-violet-50 text-violet-700 border-violet-200 text-[10px] font-semibold">
                        {notice.total_accounts} account{notice.total_accounts !== 1 ? 's' : ''}
                      </Badge>
                    </div>
                  </TableCell>

                  <TableCell className="py-3">
                    <div className="flex items-center gap-1.5 text-[12.5px] text-slate-500">
                      <Calendar className="h-3.5 w-3.5 text-slate-400 shrink-0" />
                      {notice.period_start ? formatPeriod(notice.period_start) : '—'}
                    </div>
                  </TableCell>

                  <TableCell className="py-3">
                    <div className="flex items-center gap-1.5 text-[12.5px] text-slate-500">
                      <Calendar className="h-3.5 w-3.5 text-slate-400 shrink-0" />
                      {formatDateTime(notice.generated_at)}
                    </div>
                  </TableCell>

                  <TableCell className="py-3">
                    <DropdownMenu>
                      <DropdownMenuTrigger asChild>
                        <Button
                          variant="ghost"
                          size="icon"
                          className="h-7 w-7 rounded-md text-slate-400 hover:text-violet-600 hover:bg-violet-50"
                        >
                          <MoreHorizontal className="h-3.5 w-3.5" />
                        </Button>
                      </DropdownMenuTrigger>
                      <DropdownMenuContent align="end" className="w-48 rounded-md p-1.5">
                        <DropdownMenuLabel className="text-[9px] font-bold uppercase tracking-widest text-violet-400 px-2 py-1.5">
                          Actions
                        </DropdownMenuLabel>
                        <DropdownMenuSeparator className="mb-1" />

                        <DropdownMenuItem
                          onClick={() => handleView(notice.notice_id)}
                          className="cursor-pointer rounded-md text-xs text-slate-500 focus:bg-violet-50 focus:text-violet-700 dark:focus:bg-accent dark:focus:text-accent-foreground py-2 gap-2"
                        >
                          <div className="h-6 w-6 rounded-md bg-slate-100 flex items-center justify-center shrink-0">
                            <Eye className="h-3 w-3 text-slate-500" />
                          </div>
                          <span>View details</span>
                        </DropdownMenuItem>

                        <PdfExportButton
                          noticeId={notice.notice_id}
                          variant="dropdown-item"
                        />
                      </DropdownMenuContent>
                    </DropdownMenu>
                  </TableCell>
                </TableRow>
              ))}
            </TableBody>
          </Table>
        </div>
      </div>

      {/* Pagination */}
      {!isLoading && (
        <TablePagination
          page={safePage}
          pageSize={pageSize}
          total={filtered.length}
          onPageChange={setPage}
        />
      )}
    </div>
  )
}

export default DisconnectionNoticePage