function formatPeso(amount: number): string {
  return new Intl.NumberFormat('en-PH', { style: 'currency', currency: 'PHP' }).format(amount)
}

const PAGE_SIZE = 8

// ─── Barangay Filter (dropdown with its own search) ────────────────────────

function BarangayFilter({
  barangays,
  value,
  onChange,
}: {
  barangays: string[]
  value: string
  onChange: (v: string) => void
}) {
  const [barangaySearch, setBarangaySearch] = useState('')
  const debouncedBarangaySearch = useDebouncedSearch(barangaySearch)
  const [dropdownOpen, setDropdownOpen] = useState(false)

  const filteredBarangays = debouncedBarangaySearch
    ? barangays.filter((b) => b.toLowerCase().includes(debouncedBarangaySearch.toLowerCase()))
    : barangays

  const isActive = value !== 'all'

  return (
    <DropdownMenu
      open={dropdownOpen}
      onOpenChange={(o) => {
        setDropdownOpen(o)
        if (!o) setBarangaySearch('')
      }}
    >
      <DropdownMenuTrigger asChild>
        <Button
          variant="outline"
          size="sm"
          className={cn(
            'h-8 gap-1.5 text-xs font-medium rounded-md shrink-0',
            isActive && 'border-rose-400 bg-rose-50 text-rose-700 hover:bg-rose-100 hover:border-rose-500',
          )}
        >
          <MapPin className="h-3.5 w-3.5 shrink-0" />
          {isActive ? value : 'Barangay'}
          <ChevronDown className="h-3 w-3 shrink-0 opacity-60" />
        </Button>
      </DropdownMenuTrigger>

      <DropdownMenuContent align="start" className="w-60 p-2 rounded-md">
        <div className="relative mb-2">
          <Search className="absolute left-2.5 top-1/2 -translate-y-1/2 h-3 w-3 text-slate-400" />
          <Input
            value={barangaySearch}
            onChange={(e) => setBarangaySearch(e.target.value)}
            placeholder="Search barangay"
            className="h-7 pl-7 text-xs rounded-md"
            onClick={(e) => e.stopPropagation()}
          />
        </div>
        <ScrollArea className="max-h-52">
          <DropdownMenuRadioGroup value={value} onValueChange={onChange}>
            <DropdownMenuRadioItem value="all" className="cursor-pointer rounded-md text-xs">
              All Barangays
            </DropdownMenuRadioItem>
            {filteredBarangays.length === 0 && (
              <p className="px-2 py-2 text-xs text-slate-400">No matches</p>
            )}
            {filteredBarangays.map((b) => (
              <DropdownMenuRadioItem key={b} value={b} className="cursor-pointer rounded-md text-xs">
                {b}
              </DropdownMenuRadioItem>
            ))}
          </DropdownMenuRadioGroup>
        </ScrollArea>
      </DropdownMenuContent>
    </DropdownMenu>
  )
}

interface BillingDisconnectionNoticeModalProps {
  trigger?: React.ReactNode
  onSuccess?: () => void
}

export function BillingDisconnectionNoticeModal({
  trigger,
  onSuccess,
}: BillingDisconnectionNoticeModalProps) {
  const [open, setOpen] = useState(false)
  const [isLoading, setIsLoading] = useState(false)
  const [isSubmitting, setIsSubmitting] = useState(false)

  const [period, setPeriod] = useState<ReadingPeriodOption | null>(null)
  const [rule, setRule] = useState<DisconnectionRule | null>(null)

  const [accounts, setAccounts] = useState<EligibleMeterAccount[]>([])
  const [selected, setSelected] = useState<Set<string>>(new Set())
  const [search, setSearch] = useState('')
  const debouncedSearch = useDebouncedSearch(search)
  const [barangayFilter, setBarangayFilter] = useState('all')
  const [page, setPage] = useState(1)

  // ── Load data whenever modal opens ──────────────────────────────
  const loadData = useCallback(async () => {
    setIsLoading(true)
    setSelected(new Set())
    setAccounts([])
    setPage(1)
    setBarangayFilter('all')
    try {
      const periodRes = await getCurrentReadingPeriod()
      if (periodRes.status !== 'success' || !periodRes.data) {
        toast.error('No reading period found')
        return
      }
      setPeriod(periodRes.data)

      const eligibleRes = await getEligibleMeterAccounts({
        readingPeriodId: periodRes.data.reading_period_id,
      })

      if (eligibleRes.status !== 'success') {
        toast.error(eligibleRes.message || 'Failed to load eligible accounts')
        return
      }

      setAccounts(eligibleRes.data ?? [])
      if (eligibleRes.rule) setRule(eligibleRes.rule)
    } catch (err) {
      console.error(err)
      toast.error('Failed to load disconnection data')
    } finally {
      setIsLoading(false)
    }
  }, [])

  const handleOpenChange = (next: boolean) => {
    setOpen(next)
    if (next) loadData()
    else {
      setSearch('')
      setBarangayFilter('all')
      setSelected(new Set())
      setPage(1)
    }
  }

  // ── Distinct barangay options from loaded accounts ────────────────
  const barangayOptions = useMemo(() => {
    const names = new Set<string>()
    accounts.forEach((a) => {
      if (a.barangay_name) names.add(a.barangay_name)
    })
    return Array.from(names).sort((a, b) => a.localeCompare(b))
  }, [accounts])

  // ── Filtering (search + barangay) ─────────────────────────────────
  const filtered = useMemo(() => {
    const q = debouncedSearch.trim().toLowerCase()
    return accounts.filter((a) => {
      if (barangayFilter !== 'all' && a.barangay_name !== barangayFilter) return false
      if (
        q &&
        !a.consumer_name.toLowerCase().includes(q) &&
        !(a.meter_serial_no ?? '').toLowerCase().includes(q) &&
        !a.barangay_name.toLowerCase().includes(q)
      ) {
        return false
      }
      return true
    })
  }, [accounts, debouncedSearch, barangayFilter])

  const totalPages = Math.max(1, Math.ceil(filtered.length / PAGE_SIZE))
  const safePage = Math.min(page, totalPages)
  const paginated = useMemo(
    () => filtered.slice((safePage - 1) * PAGE_SIZE, safePage * PAGE_SIZE),
    [filtered, safePage],
  )

  const handleSearchChange = (v: string) => {
    setSearch(v)
    setPage(1)
  }

  const handleBarangayChange = (v: string) => {
    setBarangayFilter(v)
    setPage(1)
  }

  const hasActiveFilters = debouncedSearch.trim().length > 0 || barangayFilter !== 'all'

  const clearFilters = () => {
    setSearch('')
    setBarangayFilter('all')
    setPage(1)
  }

  // "select all" only applies to the current page — safer & clearer with pagination
  const allPageSelected = paginated.length > 0 && paginated.every((a) => selected.has(a.meter_account_id))

  const toggleOne = (id: string) => {
    setSelected((prev) => {
      const next = new Set(prev)
      next.has(id) ? next.delete(id) : next.add(id)
      return next
    })
  }

  const togglePage = () => {
    setSelected((prev) => {
      const next = new Set(prev)
      if (allPageSelected) {
        paginated.forEach((a) => next.delete(a.meter_account_id))
      } else {
        paginated.forEach((a) => next.add(a.meter_account_id))
      }
      return next
    })
  }

  const selectAllFiltered = () => {
    setSelected((prev) => {
      const next = new Set(prev)
      filtered.forEach((a) => next.add(a.meter_account_id))
      return next
    })
  }

  const clearSelection = () => setSelected(new Set())

  const selectedAccounts = useMemo(
    () => accounts.filter((a) => selected.has(a.meter_account_id)),
    [accounts, selected],
  )
  const selectedTotal = selectedAccounts.reduce((sum, a) => sum + a.outstanding_balance, 0)

  // ── Notify only (no notice_of_disconnection created) ─────────────
  const handleSubmit = async () => {
    if (selectedAccounts.length === 0) {
      toast.error('Select at least one account')
      return
    }
    if (!period) return

    setIsSubmitting(true)
    try {
      const result = await notifyDisconnectionWarnings(
        selectedAccounts.map((a) => ({
          meter_account_id: a.meter_account_id,
          billing_id: a.billing_id,
          balance_snapshot: a.outstanding_balance,
          months_unpaid: a.unpaid_months,
        })),
      )

      if (result.status === 'error') {
        toast.error(result.message || 'Failed to notify consumers')
        return
      }

      toast.success(result.message || 'Consumers notified')
      setOpen(false)
      onSuccess?.()
    } catch (err) {
      console.error(err)
      toast.error('Failed to notify consumers')
    } finally {
      setIsSubmitting(false)
    }
  }

  const handleAutoGenerateAll = async () => {
    if (!period) return
    setIsSubmitting(true)
    try {
      const result = await autoGenerateDisconnectionNotices({
        readingPeriodId: period.reading_period_id,
      })
      if (result.status === 'error') {
        toast.error(result.message || 'Failed to notify eligible consumers')
        return
      }
      toast.success(result.message || 'Consumers notified')
      setOpen(false)
      onSuccess?.()
    } catch (err) {
      console.error(err)
      toast.error('Failed to notify eligible consumers')
    } finally {
      setIsSubmitting(false)
    }
  }

  return (
    <Dialog open={open} onOpenChange={handleOpenChange}>
      <DialogTrigger asChild>
        {trigger ?? (
          <Button
            variant="outline"
            size="sm"
            className="h-9 rounded-lg text-[13px] font-semibold gap-2 px-4 bg-white border-2 border-rose-200 text-rose-700 hover:border-rose-400 hover:bg-rose-50"
          >
            <AlertTriangle className="h-3.5 w-3.5" />
            Notify Disconnection
          </Button>
        )}
      </DialogTrigger>

      <DialogContent className="w-[95vw] sm:max-w-3xl p-0 gap-0 rounded-lg overflow-hidden">
        {/* Header */}
        <DialogHeader className="px-4 sm:px-6 py-4 border-b border-slate-100 bg-gradient-to-r from-rose-50 to-white">
          <div className="flex items-center gap-2.5 pr-6">
            <div className="h-8 w-8 rounded-md bg-rose-100 border border-rose-200 flex items-center justify-center shrink-0">
              <ShieldAlert className="h-4 w-4 text-rose-600" />
            </div>
            <div className="min-w-0">
              <DialogTitle className="text-[15px] font-bold text-slate-800">
                Notify Disconnection Warning
              </DialogTitle>
              <DialogDescription className="text-xs text-slate-400 truncate">
                {period ? period.label : 'Loading period...'}
                <span className="text-slate-500"> · notifies consumers only (no notice document)</span>
              </DialogDescription>
            </div>
          </div>
        </DialogHeader>

        {/* Rule banner */}
        {rule && (
          <div className="px-4 sm:px-6 py-2.5 bg-amber-50 border-b border-amber-100 flex items-start gap-2">
            <AlertTriangle className="h-3.5 w-3.5 text-amber-500 shrink-0 mt-0.5" />
            <p className="text-[11px] text-amber-700 leading-relaxed">
              Eligible: outstanding balance ≥{' '}
              <span className="font-semibold whitespace-nowrap">{formatPeso(rule.min_balance)}</span> or unpaid for ≥{' '}
              <span className="font-semibold whitespace-nowrap">{rule.min_unpaid_months} month(s)</span>
            </p>
          </div>
        )}

        {/* Search + Barangay filter + counts */}
        <div className="px-4 sm:px-6 py-3 border-b border-slate-100 flex flex-wrap items-center gap-2">
          <div className="relative flex-1 min-w-[180px]">
            <Search className="absolute left-3 top-1/2 -translate-y-1/2 h-3.5 w-3.5 text-slate-300" />
            <Input
              placeholder="Search consumer, serial no., or barangay…"
              value={search}
              onChange={(e) => handleSearchChange(e.target.value)}
              className="h-8 pl-9 text-xs rounded-md"
            />
            {search && (
              <button
                onClick={() => handleSearchChange('')}
                className="absolute right-2.5 top-1/2 -translate-y-1/2 p-0.5 rounded-full hover:bg-slate-100"
              >
                <X className="h-3 w-3 text-slate-400" />
              </button>
            )}
          </div>

          <BarangayFilter
            barangays={barangayOptions}
            value={barangayFilter}
            onChange={handleBarangayChange}
          />

          {hasActiveFilters && (
            <button
              onClick={clearFilters}
              className="inline-flex items-center gap-1 h-8 px-2 rounded-md text-[11px] text-slate-400 hover:text-rose-600 hover:bg-rose-50 shrink-0"
            >
              <X className="h-3 w-3" /> Clear
            </button>
          )}

          <Badge variant="outline" className="h-8 px-2.5 rounded-md text-[11px] text-slate-500 border-slate-200 whitespace-nowrap ml-auto">
            {filtered.length} eligible
          </Badge>
          <Badge className="h-8 px-2.5 rounded-md text-[11px] font-semibold bg-rose-50 text-rose-700 ring-1 ring-rose-200 whitespace-nowrap">
            {selected.size} selected
          </Badge>
        </div>

        {/* Bulk select row — only useful once there's more than a page's worth */}
        {!isLoading && filtered.length > PAGE_SIZE && (
          <div className="px-4 sm:px-6 py-1.5 border-b border-slate-100 bg-slate-50/50 flex items-center gap-3">
            <button
              onClick={selectAllFiltered}
              className="text-[11px] font-medium text-violet-600 hover:text-violet-700"
            >
              Select all {filtered.length} filtered
            </button>
            {selected.size > 0 && (
              <>
                <span className="text-slate-300">·</span>
                <button
                  onClick={clearSelection}
                  className="text-[11px] font-medium text-slate-400 hover:text-slate-600"
                >
                  Clear selection
                </button>
              </>
            )}
          </div>
        )}

        {/* Table — fixed row count per page, no internal scroll needed */}
        <div className="overflow-x-auto">
          <Table className="min-w-[640px]">
            <TableHeader>
              <TableRow className="bg-slate-50/60">
                <TableHead className="w-10">
                  <Checkbox
                    checked={allPageSelected}
                    onCheckedChange={togglePage}
                    disabled={paginated.length === 0}
                    className="rounded-md"
                  />
                </TableHead>
                <TableHead className="text-[9px] font-bold text-slate-400 uppercase tracking-wider">Consumer</TableHead>
                <TableHead className="text-[9px] font-bold text-slate-400 uppercase tracking-wider">Serial No.</TableHead>
                <TableHead className="text-[9px] font-bold text-slate-400 uppercase tracking-wider">Barangay</TableHead>
                <TableHead className="text-right text-[9px] font-bold text-slate-400 uppercase tracking-wider">Balance</TableHead>
                <TableHead className="text-right text-[9px] font-bold text-slate-400 uppercase tracking-wider whitespace-nowrap">Unpaid Mos.</TableHead>
              </TableRow>
            </TableHeader>
            <TableBody>
              {isLoading && [...Array(PAGE_SIZE)].map((_, i) => (
                <TableRow key={i}>
                  <TableCell colSpan={6} className="py-3">
                    <div className="h-3.5 w-full bg-slate-100 animate-pulse rounded-full" />
                  </TableCell>
                </TableRow>
              ))}

              {!isLoading && filtered.length === 0 && (
                <TableRow>
                  <TableCell colSpan={6} className="h-48 text-center">
                    <div className="flex flex-col items-center gap-2">
                      <ShieldAlert className="h-6 w-6 text-slate-300" />
                      <p className="text-sm font-medium text-slate-500">No eligible accounts found</p>
                      <p className="text-xs text-slate-400">
                        {accounts.length === 0
                          ? 'No accounts currently meet the disconnection rule.'
                          : 'No results match your search or filter.'}
                      </p>
                      {hasActiveFilters && accounts.length > 0 && (
                        <button
                          onClick={clearFilters}
                          className="inline-flex items-center gap-1.5 h-7 px-3 rounded-md text-xs font-medium text-rose-600 bg-rose-50 border border-rose-200 hover:bg-rose-100"
                        >
                          Clear filters
                        </button>
                      )}
                    </div>
                  </TableCell>
                </TableRow>
              )}

              {!isLoading && paginated.map((a) => {
                const isChecked = selected.has(a.meter_account_id)
                return (
                  <TableRow
                    key={a.meter_account_id}
                    onClick={() => toggleOne(a.meter_account_id)}
                    className={cn(
                      'cursor-pointer border-t border-slate-100 transition-colors',
                      isChecked ? 'bg-rose-50/60 hover:bg-rose-50' : 'hover:bg-slate-50',
                    )}
                  >
                    <TableCell onClick={(e) => e.stopPropagation()}>
                      <Checkbox
                        checked={isChecked}
                        onCheckedChange={() => toggleOne(a.meter_account_id)}
                        className="rounded-md"
                      />
                    </TableCell>
                    <TableCell className="py-2.5 text-[12.5px] font-medium text-slate-800 whitespace-nowrap">
                      {a.consumer_name}
                    </TableCell>
                    <TableCell className="py-2.5 text-[12.5px] font-mono text-slate-600 whitespace-nowrap">
                      {a.meter_serial_no}
                    </TableCell>
                    <TableCell className="py-2.5 text-[12px] text-slate-500 whitespace-nowrap">
                      {a.barangay_name || '—'}
                    </TableCell>
                    <TableCell className="py-2.5 text-right text-[12.5px] font-semibold tabular-nums text-rose-600 whitespace-nowrap">
                      {formatPeso(a.outstanding_balance)}
                    </TableCell>
                    <TableCell className="py-2.5 text-right whitespace-nowrap">
                      <Badge className="rounded-md bg-amber-50 text-amber-700 ring-1 ring-amber-200 text-[10px] font-semibold">
                        {a.unpaid_months} mo{a.unpaid_months !== 1 ? 's' : ''}
                      </Badge>
                    </TableCell>
                  </TableRow>
                )
              })}
            </TableBody>
          </Table>
        </div>

        {!isLoading && (
          <TablePagination
            page={safePage}
            pageSize={PAGE_SIZE}
            total={filtered.length}
            onPageChange={setPage}
            className="px-4 sm:px-6 py-2.5 border-t border-slate-100"
          />
        )}

        {/* Footer */}
        <DialogFooter className="px-4 sm:px-6 py-3.5 border-t border-slate-100 bg-slate-50/50 flex-col sm:flex-row items-stretch sm:items-center justify-between gap-2.5">
          <p className="text-[11px] text-slate-400">
            {selected.size > 0 ? (
              <>
                <span className="font-semibold text-slate-600">{selected.size}</span> account
                {selected.size !== 1 ? 's' : ''} · total outstanding{' '}
                <span className="font-semibold text-rose-600">{formatPeso(selectedTotal)}</span>
              </>
            ) : (
              'No accounts selected'
            )}
          </p>
          <div className="flex flex-wrap gap-2 shrink-0 justify-end">
            <Button
              variant="outline"
              size="sm"
              className="h-8 rounded-md text-xs"
              onClick={() => setOpen(false)}
              disabled={isSubmitting}
            >
              Cancel
            </Button>
            <Button
              variant="outline"
              size="sm"
              className="h-8 rounded-md text-xs border-rose-200 text-rose-700 hover:bg-rose-50 gap-1.5"
              onClick={handleAutoGenerateAll}
              disabled={isSubmitting || !period || accounts.length === 0}
            >
              {isSubmitting && <Spinner />}
              Notify all eligible
            </Button>
            <Button
              size="sm"
              className="h-8 rounded-md text-xs bg-rose-600 hover:bg-rose-700 text-white gap-1.5 whitespace-nowrap"
              onClick={handleSubmit}
              disabled={isSubmitting || selected.size === 0}
            >
              {isSubmitting && <Spinner />}
              Notify selected
            </Button>
          </div>
        </DialogFooter>
      </DialogContent>
    </Dialog>
  )
}